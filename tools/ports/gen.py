"""Generates src/gen/layouts.rs and src/gen/funcs.rs from the IDA export (tools/out/*.json).

Run it after tools/ida_export_inventory.py. The output is in git, so a build needs no IDA.
"""
import json
import os
import sys
import re

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))  # the shared tools in tools/
from common import is_renderer_function

HERE = os.path.dirname(os.path.abspath(__file__))
TOOLS = os.path.dirname(HERE)
OUT = os.path.join(TOOLS, "out")
GEN = os.path.join(os.path.dirname(TOOLS), "src", "gen")

LAYOUT_RE = re.compile(
    r"^(NiDX8|NiD3D|NiRender|NiGeometryBufferData|NiPropertyState|NiDynamicEffectState|NiRenderStateSetting|"
    r"NiAlphaProperty|NiZBufferProperty|NiStencilProperty|NiFogProperty|NiMaterialProperty|NiTexturingProperty|"
    r"NiVertexColorProperty|NiProperty$|NiTransform$|NiBound$|NiFrustum$|NiObject$|NiObjectNET$|NiRefObject$|"
    r"THashMap$|THashMap::Node$|NiGeometryData$|NiTriBasedGeomData$|NiTriShapeData$|NiTriStripsData$|"
    r"NiSkinInstance$|NiSkinPartition|NiSourceTexture$|NiTexture$|NiPixelData$|NiPixelFormat$|NiLight$|"
    r"NiDynamicEffect$|NiAVObject$|NiGeometry$|NiCamera$|NiColor$|NiColorA$|D3DMATERIAL|D3DLIGHT8$|"
    r"D3DVIEWPORT8$|D3DCAPS8$|D3DPRESENT_PARAMETERS|"
    r"NiNode$|NiSwitchNode$|NiFltAnimationNode$|NiBSPNode$|NiBillboardNode$|NiSortAdjustNode$|NiPlane$|"
    r"NiAccumulator$|NiClusterAccumulator|NiAlphaAccumulator$|NiParticles$|NiParticlesData$|NiLines$|NiLinesData$|"
    r"NiTimeController$|NiTriShape$|NiAutoNormalParticles$|NiScreenPolygon$|"
    r"BSAnimationNode$|NiLODNode$|NiLODData$|NiTriStrips$|NiTriBasedGeometry$|"
    # The hand-written offsets moved here (tools/hand_offsets.py), from 2026-10-24.
    r"NiSkinData$|NiBoneData$|WorldController$|PlayerAnimController$|NiTextureEffect$|vec3$|"
    r"InterfaceNiDX8TextureData$|DataHandler$|ShadowManager$|WaterController$|WeatherController$|Moon$|"
    r"InterfaceNiLight$|TES3Game$|TES3WaterNVLake$|NVSkyRenderToTexture$|TListItem$|InterfaceNiObject$|"
    r"InterfaceNiAccumulator$|InterfaceNiRenderer$|InterfaceNiAVObject$|TArray$|NiStream$|NiPalette$|"
    r"NiBltSource$|InterfaceNiTexture$|NiImageConverter::vtbl$|NiFormatPrefs$|NiTListBase$|NiTListAllocator::Data$|"
    r"D3DADAPTER_IDENTIFIER8$|InterfaceNiGeometryData$|InterfaceNiTimeController$|NiRTTI$|NiDirectionalLight$|"
    r"NiPointLight$|NiSpotLight$|NiTexture::RendererData$|NiDX8VertexBufferManager$|NiDX8IndexBufferManager$|"
    r"NiDX8TextureManager$|NiDX8LightManager$|InterfaceNiTriBasedGeomData$|NiRendererSpecificProperty::RenderData7$|"
    r"NiDX8SourceTextureData$|WorldControllerRenderTarget$|Cell$|CellMappingVisuals$|"
    r"NiRendererSpecificProperty::RenderData_vtbl$|InterfaceTHashMap$)")


KEYWORDS = {"type", "super", "self", "ref", "match", "loop", "move", "fn", "mod", "use", "in", "final", "box", "priv", "enum",
            "struct", "union", "static", "const", "where", "impl", "trait", "true", "false", "as", "if", "else", "for",
            "while", "return", "break", "continue", "crate", "pub", "let", "mut", "unsafe", "extern", "dyn", "async",
            "await", "abstract", "become", "do", "macro", "override", "typeof", "unsized", "virtual", "yield", "try"}


def ident(name):
    name = re.sub(r"[^0-9A-Za-z_]", "_", name)
    if not name or name[0].isdigit():
        name = "_" + name
    if name.lower() in KEYWORDS:
        name += "_"
    return name


def flatten(structs, name, base=0, prefix="", depth=0):
    for m in structs[name]["members"]:
        mname = prefix + (m["name"] or "anon_%x" % m["offset"])
        yield mname, base + m["offset"], m["size"], m["type"]
        inner = structs.get(m["type"])
        if inner and not inner["union"] and depth < 4:
            # A base class adds no prefix. The name is NiAlphaProperty::flags, not super_flags.
            inner_prefix = prefix if m["name"] == "super" else mname + "_"
            yield from flatten(structs, m["type"], base + m["offset"], inner_prefix, depth + 1)


def gen_layouts(structs):
    out = ["// Generated by tools/gen.py from the IDA database. Do not edit.",
           "#![allow(non_snake_case, non_upper_case_globals, dead_code)]", ""]
    for name in sorted(structs):
        if not LAYOUT_RE.search(name):
            continue
        s = structs[name]
        out.append("pub mod %s {" % ident(name.replace("::", "_")))
        out.append("    pub const SIZE: usize = 0x%x;" % s["size"])
        seen = set()
        for mname, off, size, mtype in flatten(structs, name):
            mid = ident(mname)
            while mid in seen or mid == "SIZE":
                mid += "_"
            seen.add(mid)
            out.append("    /// `%s`, 0x%x bytes" % (mtype.replace("`", "'"), size))
            out.append("    pub const %s: usize = 0x%x;" % (mid, off))
        out.append("}")
        out.append("")
    return "\n".join(out)


# The bytes of stack arguments that a function removes, where the database has 0 and the code
# says another number. Three functions end in a jump to a function that removes the
# arguments. For the fourth the type in the database has no argument, and the code ends in
# `retn 4`.
ARGSIZE = {
    0x6AC370: 12,  # NiDX8Renderer::PrecacheTexture: jmp to NiDX8TextureManager::PrecacheTexture
    0x6F53E0: 16,  # NiRenderer::BatchRenderShape: jmp to RenderShape
    0x6F53F0: 16,  # NiRenderer::BatchRenderStrips: jmp to RenderTriStrips
    0x6F5650: 4,   # NiRenderer::SetLeftRightSwap
}


def gen_funcs(funcs):
    rows = []
    code = bytearray()
    for f in sorted(funcs, key=lambda f: f["ea"]):
        if not is_renderer_function(f["name"]):
            continue
        f = dict(f, argsize=ARGSIZE.get(f["ea"], f["argsize"]))
        offset = len(code)
        code += bytes.fromhex(f["bytes"])
        head = bytes.fromhex(f["head"]).ljust(16, b"\0")
        rows.append("    Func { ea: 0x%x, size: %d, name: \"%s\", argsize: %d, code: 0x%x, steal: %d, pic: %s, relocs: [%d, %d], head: [%s] }," % (
            f["ea"], f["size"], f["name"].replace('"', "'"), f["argsize"], offset, f["steal"], "true" if f["steal_pic"] else "false", *(f["relocs"] + [0, 0])[:2],
            ", ".join("0x%02x" % b for b in head)))
    open(os.path.join(GEN, "code.bin"), "wb").write(code)
    return "\n".join([
        "// Generated by tools/gen.py from the IDA database. Do not edit.",
        "/// One function of the renderer subsystem as the IDA database has it.",
        "pub struct Func {",
        "    pub ea: usize,",
        "    pub size: usize,",
        "    pub name: &'static str,",
        "    /// Bytes of stack arguments the function removes at return (0 for cdecl).",
        "    pub argsize: usize,",
        "    /// Where the `size` bytes of the function in the database start in [`CODE`].",
        "    pub code: usize,",
        "    /// Bytes a 5-byte jump at the entry displaces (whole instructions).",
        "    pub steal: usize,",
        "    /// The displaced instructions run unchanged at another address.",
        "    pub pic: bool,",
        "    /// Offsets in the displaced bytes of 32-bit relative targets, which move with the code. 0 = none.",
        "    pub relocs: [u8; 2],",
        "    pub head: [u8; 16],",
        "}",
        "",
        "/// The bytes of every function in the table, as the database has them.",
        "pub static CODE: &[u8] = include_bytes!(\"code.bin\");",
        "",
        "pub static FUNCS: [Func; %d] = [" % len(rows),
        *rows,
        "];",
        "",
    ])


def main():
    structs = json.load(open(os.path.join(OUT, "structs.json")))
    os.makedirs(GEN, exist_ok=True)
    open(os.path.join(GEN, "layouts.rs"), "w", newline="\n").write(gen_layouts(structs))
    # `--layouts-only` leaves the function table and its bytes alone: a new struct for the
    # layouts does not change the ports' byte checks.
    if "--layouts-only" in sys.argv:
        print("layouts written")
        return
    funcs = json.load(open(os.path.join(OUT, "inventory.json")))
    open(os.path.join(GEN, "funcs.rs"), "w", newline="\n").write(gen_funcs(funcs))
    print("layouts and funcs written")


if __name__ == "__main__":
    main()
