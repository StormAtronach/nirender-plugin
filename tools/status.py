"""Writes STATUS.md: what is ported and what the last game run measured.

Inputs: tools/out/inventory.json (the functions), src/ports/*.rs (the ports), and the newest
results/*/report.tsv and nirender.log.

    python tools/status.py
"""
import glob
import json
import os
import re
import time
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
FUNC_RE = re.compile(r"^(NiDX8|NiD3D|NiRenderState|NiRenderer|NiGetD3DFormat|NiPropertyState)")
FUNC_SKIP = re.compile(r"_SEH$|NiDX8Application|NiDX8SelectResolution|StdMap")
PORT_RE = re.compile(r"port_(?:thiscall|cdecl)!\(\s*\w+,\s*0x([0-9A-Fa-f]+)")


def class_of(name):
    return name.split("::")[0].replace("_static", "")


def newest_run():
    """The newest run that got as far as a report."""
    runs = sorted(d for d in glob.glob(os.path.join(REPO, "results", "*")) if os.path.isfile(os.path.join(d, "report.tsv")))
    return runs[-1] if runs else None


def main():
    inventory = json.load(open(os.path.join(HERE, "out", "inventory.json")))
    funcs = [f for f in inventory if FUNC_RE.search(f["name"]) and not FUNC_SKIP.search(f["name"])]

    ported = set()
    for path in glob.glob(os.path.join(REPO, "src", "ports", "*.rs")):
        ported |= {int(m, 16) for m in PORT_RE.findall(open(path, encoding="utf-8").read())}

    report, changed, frame_lines, run = {}, set(), [], newest_run()
    if run:
        lines = open(os.path.join(run, "report.tsv"), encoding="utf-8").read().splitlines()
        header = lines[0].split("\t")
        for line in lines[1:]:
            if line.strip():
                row = dict(zip(header, line.split("\t")))
                report[int(row["addr"], 16)] = row
        log = os.path.join(run, "nirender.log")
        if os.path.isfile(log):
            for line in open(log, encoding="utf-8", errors="replace"):
                m = re.match(r"census: 0x[0-9a-f]+ (\S+)\+0x", line)
                if m:
                    changed.add(m.group(1))
                if line.startswith("frame test"):
                    frame_lines.append(line.strip()[:160])

    classes = defaultdict(lambda: {"functions": 0, "bytes": 0, "ported": 0, "ported_bytes": 0, "clean": 0, "different": 0, "changed": 0})
    rows = []
    for f in funcs:
        c = classes[class_of(f["name"])]
        c["functions"] += 1
        c["bytes"] += f["size"]
        if f["name"] in changed:
            c["changed"] += 1
        if f["ea"] not in ported:
            continue
        c["ported"] += 1
        c["ported_bytes"] += f["size"]
        row = report.get(f["ea"])
        if row is None:
            state = "ported, not run yet"
        elif row.get("locked") == "true":
            state = "locked (a mod rewrote the function)"
        elif row["installed"] != "true":
            state = "NO DETOUR"
        elif int(row["mismatches"]):
            state = "DIFFERENT"
            c["different"] += 1
        elif int(row["shadow_calls"]):
            state = "clean"
            c["clean"] += 1
        elif int(row["live_calls"]):
            state = "ran live only"
        else:
            state = "not called in the run"
        rows.append((f["name"], f["ea"], state, row or {}))

    total = lambda key: sum(c[key] for c in classes.values())
    out = ["# Status", "",
           "Generated by `tools/status.py` on %s. Do not edit." % time.strftime("%Y-%m-%d %H:%M"), "",
           "Last game run: `%s`" % (os.path.basename(run) if run else "none"), "",
           "| | functions | code bytes |", "| --- | ---: | ---: |",
           "| Renderer subsystem | %d | %d |" % (total("functions"), total("bytes")),
           "| Ported | %d | %d |" % (total("ported"), total("ported_bytes")),
           "| Compared in the game with 0 differences | %d | |" % total("clean"),
           "| Compared with differences | %d | |" % total("different"),
           "| Changed in memory by another mod | %d | |" % total("changed"), "",
           "## By class", "",
           "| class | functions | ported | clean | different | changed by a mod |", "| --- | ---: | ---: | ---: | ---: | ---: |"]
    for name, c in sorted(classes.items(), key=lambda kv: -kv[1]["bytes"]):
        out.append("| %s | %d | %d | %d | %d | %d |" % (name, c["functions"], c["ported"], c["clean"], c["different"], c["changed"]))
    out += ["", "## Ports", "",
            "| function | address | state | calls compared | different | not compared | calls as Rust |",
            "| --- | --- | --- | ---: | ---: | ---: | ---: |"]
    for name, ea, state, row in rows:
        out.append("| %s | 0x%x | %s | %s | %s | %s | %s |" % (
            name, ea, state, row.get("shadow_calls", ""), row.get("mismatches", ""), row.get("skipped", ""), row.get("live_calls", "")))
    if frame_lines:
        out += ["", "## Frame tests of the last run", ""] + ["- " + line for line in frame_lines]
    if changed:
        out += ["", "## Functions another mod changed in memory", ""] + ["- " + name for name in sorted(changed)]
    open(os.path.join(REPO, "STATUS.md"), "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
    print("STATUS.md: %d of %d functions ported, %d clean, %d different" % (
        total("ported"), total("functions"), total("clean"), total("different")))


if __name__ == "__main__":
    main()
